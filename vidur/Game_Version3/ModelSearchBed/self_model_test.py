@dataclass(frozen=True)
class SelfModelTestConfig:
    """Configuration for one local model-search experiment."""

    dataset_dir: Path
    output_dir: Path

    # Dataset/root-storage settings. Existing datasets are reused by default.
    # Generation is only allowed when `allow_dataset_generation=True`.
    num_roots: int = 10_000
    max_candidate_roots: int = 100_000
    candidate_batch_size: int = 1_024
    min_nonzero_target_ratio: float = 0.50
    target_abs_threshold: float = DEFAULT_NONZERO_EPS
    history_hops_min: int = 0
    history_hops_max: int = 200
    seed: int = 2027
    num_processes: int = 1
    root_player_filter: str = "controller"
    allow_dataset_generation: bool = False

    # Train/eval split settings.
    eval_ratio: float = 0.20
    split_seed: int = 12345

    # Experiment identity and generic batching. Architecture/training-specific
    # settings live in `extra_config` so this harness does not constrain model
    # design choices.
    model_name: str = "baseline_value_model"
    batch_size: int = 256
    extra_config: dict[str, Any] = field(default_factory=dict)

    # Output/logging settings.
    metrics_csv_name: str = "self_model_test_metrics.csv"
    checkpoint_name: str = "best_model.pt"


