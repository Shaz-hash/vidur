"""Run local GV3 model-search experiments on a fixed root-state dataset.

This is the second stage of the ModelSearchBed workflow.

High-level purpose:
    1. Load fixed root states generated by `root_storage.py`.
    2. Reuse an existing root dataset by default.
    3. Pass train/eval root records to `DNN/trainer.py`.
    4. Ask `DNN/infer.py` for model predictions on stored states.
    5. Compute train/eval MSE, MAE, and max absolute error in this harness.
    6. Record metrics to CSV so architectures/features can be compared.

Architecture-search boundary:
    This file should not decide the feature schema, model class, loss function,
    or inference representation. Agents trying new approaches should modify
    `DNN/infer.py`, model files, and `DNN/trainer.py`. This harness only owns
    fixed dataset generation/loading, deterministic splitting, and metric
    computation.

Fallback:
    Until custom hooks are added to `trainer.py` and `infer.py`, this file keeps
    a fallback adapter that uses the current GV3 `AlphaZeroModel` stack. That is
    only for smoke testing the harness.

Important scope:
    This file is for local architecture experiments. It should not use the GV3
    distributed network runner, SSH, or EC2 worker orchestration.
"""

